"""
Biometric Cryptography & Privacy Utility
=========================================

Provides cryptographic protection for biometric data at rest in compliance
with GDPR (Article 9 / 17), BIPA, and CCPA/CPRA regulations:

1. AES-256-GCM / Fernet encryption of raw face embedding vectors at rest.
2. Key derivation from system secrets (``BIOMETRIC_ENCRYPTION_KEY`` or ``SECRET_KEY``).
3. Cryptographic shredding (NIST SP 800-88 / DoD 5220.22-M compliant multi-pass
   file overwriting before unlinking) for permanent biometric deletion.
4. Transparent file encryption/decryption for exported biometrics or cache files.
"""

from __future__ import annotations

import base64
import hashlib
import logging
import os
import secrets
from pathlib import Path
from typing import Optional, Union

import numpy as np
from cryptography.fernet import Fernet
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.kdf.pbkdf2 import PBKDF2HMAC

logger = logging.getLogger(__name__)

# Standard constant salt for key derivation when an explicit key is not provided
_DEFAULT_SALT = b"FaceRecognitionAI_Biometric_Salt_v2.1"


def get_biometric_cipher(secret_key: Optional[str] = None) -> Fernet:
    """Return a Fernet cipher derived from the environment or provided secret.

    Derives a high-entropy 32-byte key using PBKDF2-HMAC-SHA256 with 100,000 iterations.
    """
    raw_key = (
        secret_key
        or os.getenv("BIOMETRIC_ENCRYPTION_KEY")
        or os.getenv("SECRET_KEY")
        or "face-ai-default-biometric-salt-key-2026"
    )
    kdf = PBKDF2HMAC(
        algorithm=hashes.SHA256(),
        length=32,
        salt=_DEFAULT_SALT,
        iterations=100_000,
    )
    derived_key = base64.urlsafe_b64encode(kdf.derive(raw_key.encode("utf-8")))
    return Fernet(derived_key)


def encrypt_embedding(
    vector: np.ndarray,
    cipher: Optional[Fernet] = None,
) -> bytes:
    """Encrypt a 512-D float32 numpy embedding vector to authenticated ciphertext.

    Args:
        vector: 1D or 2D numpy array representing the face embedding.
        cipher: Optional pre-configured Fernet cipher.

    Returns:
        Encrypted ciphertext bytes.
    """
    if cipher is None:
        cipher = get_biometric_cipher()

    arr = np.ascontiguousarray(vector, dtype=np.float32)
    raw_bytes = arr.tobytes()
    return cipher.encrypt(raw_bytes)


def decrypt_embedding(
    ciphertext: bytes,
    dimension: int = 512,
    cipher: Optional[Fernet] = None,
) -> np.ndarray:
    """Decrypt authenticated ciphertext back into a 512-D float32 numpy embedding vector.

    Args:
        ciphertext: Encrypted bytes generated by ``encrypt_embedding``.
        dimension: Expected number of float32 elements (default 512 for ArcFace).
        cipher: Optional pre-configured Fernet cipher.

    Returns:
        Decrypted 1D float32 numpy array.
    """
    if cipher is None:
        cipher = get_biometric_cipher()

    raw_bytes = cipher.decrypt(ciphertext)
    arr = np.frombuffer(raw_bytes, dtype=np.float32)
    if arr.size != dimension:
        logger.warning("Decrypted embedding size %d != expected dimension %d", arr.size, dimension)
    return arr.copy()


def encrypt_file(
    source_path: Union[str, Path],
    dest_path: Optional[Union[str, Path]] = None,
    cipher: Optional[Fernet] = None,
) -> Path:
    """Encrypt a file on disk (e.g. face photo or snapshot).

    Args:
        source_path: Path to the input file.
        dest_path: Path to write encrypted output. Defaults to ``source_path.with_suffix('.enc')``.
        cipher: Optional pre-configured Fernet cipher.

    Returns:
        Path to the encrypted file.
    """
    src = Path(source_path)
    if not src.exists():
        raise FileNotFoundError(f"Source file not found: {src}")

    dst = Path(dest_path) if dest_path else src.with_suffix(src.suffix + ".enc")
    if cipher is None:
        cipher = get_biometric_cipher()

    plaintext = src.read_bytes()
    ciphertext = cipher.encrypt(plaintext)
    dst.write_bytes(ciphertext)
    return dst


def decrypt_file(
    source_path: Union[str, Path],
    dest_path: Optional[Union[str, Path]] = None,
    cipher: Optional[Fernet] = None,
) -> Path:
    """Decrypt an encrypted file on disk.

    Args:
        source_path: Path to the encrypted file.
        dest_path: Path to write decrypted output.
        cipher: Optional pre-configured Fernet cipher.

    Returns:
        Path to the decrypted file.
    """
    src = Path(source_path)
    if not src.exists():
        raise FileNotFoundError(f"Source file not found: {src}")

    if dest_path:
        dst = Path(dest_path)
    else:
        # Strip .enc if present
        dst = src.with_suffix("") if src.suffix == ".enc" else src.with_suffix(".dec")

    if cipher is None:
        cipher = get_biometric_cipher()

    ciphertext = src.read_bytes()
    plaintext = cipher.decrypt(ciphertext)
    dst.write_bytes(plaintext)
    return dst


def shred_file(path: Union[str, Path], passes: int = 3) -> bool:
    """Cryptographically shred a file on disk before deletion.

    Implements DoD 5220.22-M / NIST SP 800-88 guidelines:
    - Pass 1: Overwrite entire file with cryptographically secure random bytes
    - Pass 2: Overwrite entire file with inverted/alternate bit pattern (0xFF)
    - Pass 3: Overwrite entire file with zeros (0x00)
    - Flush and sync to disk before unlinking.

    Args:
        path: Path of the file to shred.
        passes: Number of overwrite passes (default 3).

    Returns:
        ``True`` if shredded and unlinked, ``False`` if file did not exist.
    """
    target = Path(path)
    if not target.exists() or not target.is_file():
        return False

    try:
        file_size = target.stat().st_size

        if file_size > 0:
            with open(target, "ba+", buffering=0) as f:
                for p in range(passes):
                    f.seek(0)
                    if p == 0:
                        f.write(secrets.token_bytes(file_size))
                    elif p == 1:
                        f.write(b"\xff" * file_size)
                    else:
                        f.write(b"\x00" * file_size)
                    f.flush()
                    os.fsync(f.fileno())

        target.unlink(missing_ok=True)
        logger.info("Cryptographically shredded biometric file: %s (%d bytes)", target.name, file_size)
        return True
    except Exception as exc:
        logger.warning("Error during cryptographic shredding of %s: %s", target, exc)
        # Fallback to standard unlink if shredding threw permission error
        try:
            target.unlink(missing_ok=True)
            return True
        except Exception:
            return False
